import {build} from 'vite';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

// Package the canonical functions for Supabase's single-file dashboard editor.
// Keep npm: imports external: Deno resolves their pinned versions at deployment.
process.chdir(fileURLToPath(new URL('..',import.meta.url)));
await import('./sync-contracts.mjs');
const check=process.argv.includes('--check');
await mkdir('supabase/dashboard',{recursive:true});
for(const name of ['flight-api','telemetry-ingest']){
  const sources=[`supabase/functions/${name}/index.ts`,...['contracts.ts','flight.ts','modes.ts','safety.ts'].map(f=>`supabase/functions/_shared/${f}`)];
  const hash=createHash('sha256');
  for(const source of sources)hash.update(source).update(await readFile(source));
  const banner=`// @ts-nocheck\n// Generated by pnpm functions:bundle. Edit the canonical source, then regenerate.\n// Function name: ${name}\n// Source SHA-256: ${hash.digest('hex')}\n// Uses server-side authentication. Deploy with verify_jwt=false as documented.\n`;
  const built=await build({configFile:false,publicDir:false,logLevel:'error',build:{ssr:`supabase/functions/${name}/index.ts`,target:'es2022',write:false,minify:false,sourcemap:false,rolldownOptions:{external:id=>id.startsWith('npm:'),output:{format:'es',banner,entryFileNames:`${name}.ts`}}}});
  const chunks=(Array.isArray(built)?built.flatMap(b=>b.output):built.output).filter(o=>o.type==='chunk');
  if(chunks.length!==1)throw new Error(`${name} must produce exactly one file`);
  const chunk=chunks[0];
  if(chunk.imports.some(id=>!id.startsWith('npm:'))||chunk.dynamicImports.length)throw new Error(`${name} has an unresolved local dependency`);
  const destination=`supabase/dashboard/${name}.ts`;
  if(check){if(await readFile(destination,'utf8')!==chunk.code)throw new Error(`${destination} is stale; run pnpm functions:bundle`)}
  else await writeFile(destination,chunk.code);
  console.log(`${check?'Checked':'Generated'} ${destination} (${Buffer.byteLength(chunk.code)} bytes)`);
}
